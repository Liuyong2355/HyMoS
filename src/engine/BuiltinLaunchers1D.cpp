std::shared_ptr<CouetteTask> SubmitCouette(const ConfigSnapshot& snapshot,
                                           ConfigValidation* validation) {
  CouetteConfig config;
  ConfigValidation checked = BuildCouetteConfig(snapshot, &config);
  std::string workspace;
  std::string resolved_config_path;
  if (checked.valid) {
    std::string freeze_error;
    if (!FreezeSnapshot(snapshot, &workspace, &resolved_config_path,
                        &freeze_error)) {
      checked.valid = false;
      checked.errors.push_back(freeze_error);
    }
  }
  if (validation != NULL) *validation = checked;
  if (checked.valid) {
    config.legacy_distribution_output_path = workspace + "/DisSol1th.dat";
    std::shared_ptr<CouetteTask> task(
        new CouetteTask(config, workspace, resolved_config_path));
    task->worker_ = std::thread(&CouetteTask::Run, task.get());
    return task;
  }

  std::shared_ptr<CouetteTask> task(new CouetteTask(config));
  {
    std::lock_guard<std::mutex> lock(task->result_mutex_);
    task->result_.status = CouetteStatus::InvalidConfig;
    task->result_.message = checked.Message();
  }
  task->status_.store(CouetteStatus::InvalidConfig);
  return task;
}

