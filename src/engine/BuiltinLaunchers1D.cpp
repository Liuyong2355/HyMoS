bool ReadInt(const ConfigSnapshot& snapshot, const char* key, int* value,
             ConfigValidation* validation) {
  const std::map<std::string, std::string>::const_iterator found =
      snapshot.entries.find(key);
  if (found == snapshot.entries.end()) {
    validation->errors.push_back(std::string("missing ") + key);
    return false;
  }
  char* end = NULL;
  errno = 0;
  const long parsed = std::strtol(found->second.c_str(), &end, 10);
  if (errno != 0 || end == found->second.c_str() || *end != '\0' ||
      parsed < std::numeric_limits<int>::min() ||
      parsed > std::numeric_limits<int>::max()) {
    validation->errors.push_back(std::string("invalid integer ") + key);
    return false;
  }
  *value = static_cast<int>(parsed);
  return true;
}

bool ReadDouble(const ConfigSnapshot& snapshot, const char* key, double* value,
                ConfigValidation* validation) {
  const std::map<std::string, std::string>::const_iterator found =
      snapshot.entries.find(key);
  if (found == snapshot.entries.end()) {
    validation->errors.push_back(std::string("missing ") + key);
    return false;
  }
  char* end = NULL;
  errno = 0;
  const double parsed = std::strtod(found->second.c_str(), &end);
  if (errno != 0 || end == found->second.c_str() || *end != '\0' ||
      !std::isfinite(parsed)) {
    validation->errors.push_back(std::string("invalid finite number ") + key);
    return false;
  }
  *value = parsed;
  return true;
}

bool ReadOptionalWallDouble(const ConfigSnapshot& snapshot, const char* key,
                            double fallback, bool strictly_positive,
                            ConfigValidation* validation) {
  const std::map<std::string, std::string>::const_iterator found =
      snapshot.entries.find(key);
  if (found == snapshot.entries.end()) return std::isfinite(fallback) &&
      (!strictly_positive || fallback > 0);
  char* end = NULL;
  errno = 0;
  const double parsed = std::strtod(found->second.c_str(), &end);
  if (errno != 0 || end == found->second.c_str() || *end != '\0' ||
      !std::isfinite(parsed) || (strictly_positive && parsed <= 0)) {
    validation->errors.push_back(std::string("invalid ") +
        (strictly_positive ? "positive" : "finite") + " number " + key);
    return false;
  }
  return true;
}

